import xarray as xr
import pandas as pd

# 1. Указываем путь к твоему файлу 
# (буква 'r' перед строкой обязательна, чтобы Windows правильно понял слэши)
file_path = r"C:\Users\Rifn3\Desktop\Thuas\Q4\project\KIS___OPER_P___OBS_____L2.nc"

print(f"Открываю файл: {file_path}...")

# 2. Читаем NetCDF файл и конвертируем его в удобную таблицу (DataFrame)
ds = xr.open_dataset(file_path)
df = ds.to_dataframe().reset_index()

# Закрываем оригинальный файл, чтобы не занимать память
ds.close()

# Очищаем пустые значения по скорости ветра (чтобы таблица была чище)
# Для 10-минутных или суточных данных KNMI скорость ветра обычно называется 'ff' или 'fg'.
# Если скрипт выдаст ошибку, просто закомментируй следующую строку:
# df = df.dropna(subset=['ff']) 

print(f"Файл успешно загружен! Всего строк: {len(df)}")

# ==========================================
# ВАРИАНТ 1: Вывести ВСЕ строки в консоль
# ==========================================
print("\n--- Вывод данных в консоль ---")

# Снимаем ограничения pandas на количество выводимых строк и колонок
pd.set_option('display.max_rows', None)
pd.set_option('display.max_columns', None)

# Выводим таблицу (если строк очень много, консоль может немного "подумать")
# Чтобы не зависло, давай выведем нужные колонки. Если не знаешь названия колонок, 
# замени df.head(100) на просто df, чтобы вывести всё.
print(df.head(500)) # Выводим первые 500 строк для старта

# ==========================================
# ВАРИАНТ 2: Сохранить в CSV (Самый удобный способ)
# ==========================================
csv_path = r"C:\Users\Rifn3\Desktop\Thuas\Q4\project\my_weather_data.csv"

print(f"\nСохраняю всю таблицу в файл CSV: {csv_path}...")
# Сохраняем без колонки с индексами
df.to_csv(csv_path, index=False)

print("Готово! Теперь ты можешь открыть my_weather_data.csv в Excel и просмотреть абсолютно все строки.")